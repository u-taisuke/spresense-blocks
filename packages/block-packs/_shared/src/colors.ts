/**
 * すべてのブロックパックで共通して使う配色ルール。
 *
 * Scratch や MakeCode のように「制御」「動作」などカテゴリごとに色を変えることで、
 * 初めて触る子供でもブロックの種類をひと目で区別できるようにする。
 * 新しいブロックパックを追加するときは、新しい色を増やすのではなく、
 * まずこの中から適切なカテゴリを選ぶこと(パック間で色がバラバラになるのを防ぐため)。
 *
 * 値は16進カラーコード。Blockly は数値(色相0-360)も受け付けるが、
 * それだと彩度・明度が低めで小中高校生には地味に見えるため、
 * Scratchのブロックパレットのようなはっきりした原色に近い色を直接指定している。
 */
export const BlockCategoryColour = {
  /** 制御: 「◯ミリ秒待つ」など、それ単体で完結する簡単な制御ブロック */
  CONTROL: "#FFAB19",
  /**
   * 制御構文: 「ずっと」「くり返し」「もし〜なら」など、中に他のブロックを入れて
   * プログラムの流れそのものを組み立てるブロック。同じ「制御」カテゴリの中でも
   * 一目で見分けられるよう、CONTROL より濃いオレンジにしてある。
   */
  CONTROL_STRUCTURE: "#E65100",
  /** 動作: LED・デジタル出力・PWM出力など、ハードウェアに指示を出す(書き込む)ブロック */
  ACTION: "#4C97FF",
  /** センシング: デジタル入力・アナログ入力・センサーなど、ハードウェアから値を読み取るブロック */
  SENSING: "#5CB1D6",
  /** 演算: 比較・計算など、値を作ったり判定したりするブロック */
  OPERATOR: "#59C059",
  /** 変数: 変数の読み書き */
  VARIABLE: "#9966FF",
  /** 音: 音声再生・録音などのブロック (Phase3のaudioパックで使用予定) */
  SOUND: "#CF63CF",
} as const;
